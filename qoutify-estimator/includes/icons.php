function qtf_icon( $name, $size = 20 ) {
	$paths = qtf_icon_paths();
	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}
	return '<svg class="qtf-icon" width="' . (int) $size . '" height="' . (int) $size . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' . $paths[ $name ] . '</svg>'; // phpcs:ignore WordPress.Security.EscapeOutput
}

